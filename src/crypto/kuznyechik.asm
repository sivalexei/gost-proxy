; ----------------------------------------------
;  kuznyechik_set_key
;  Вход: rdi = указатель на 32‑байтный ключ
;        rsi = указатель на массив из 10 раундовых ключей (160 байт)
; ----------------------------------------------
kuznyechik_set_key:
    push rbp
    mov rbp, rsp
    sub rsp, 64

    ; K0 и K1
    movdqu xmm0, [rdi]
    movdqu xmm1, [rdi+16]
    movdqu [rsp+16], xmm0
    movdqu [rsp+32], xmm1

    ; Сохраняем начальные ключи
    movdqu [rsi], xmm0
    movdqu [rsi+16], xmm1
    add rsi, 32                     ; теперь rsi указывает на место для K2

    mov r10d, 0                      ; g = 0..3
.key_groups:
    cmp r10d, 4
    jge .key_done

    mov ecx, 1                       ; j = 1..8
.key_rounds:
    cmp ecx, 9
    jge .key_store

    ; round_num = g*8 + (j-1)
    mov r11d, r10d
    imul r11d, 8
    lea r11d, [r11d + ecx - 1]       ; round_num = g*8 + j - 1

    ; Загружаем раундовую константу C
    lea rbx, [rel round_constants]
    lea rax, [rbx+r11]
    movzx eax, byte [rax]

    ; Подготовка C в xmm2 (0x00..00 C 00..00)
    xorps xmm2, xmm2
    movd xmm2, eax

    ; F_round: tmp = S(K0 ^ C)
    movdqu xmm3, [rsp+16]
    pxor xmm3, xmm2
    lea rdx, [rel S_box_table]
    vpshufb xmm3, xmm3, [rdx]       ; S-подстановка (неверная, но оставлена)

    ; L(tmp)
    movdqu [rsp+48], xmm3
    lea rdi, [rsp+48]
    lea r8, [rel L_table]            ; инициализируем r8
    call kuznyechik_L_avx2

    ; tmp ^= K1
    movdqu xmm4, [rsp+48]
    pxor xmm4, [rsp+32]

    ; swap K0 и K1
    movdqu xmm3, [rsp+32]
    movdqu [rsp+16], xmm3
    movdqu [rsp+32], xmm4

    inc ecx
    jmp .key_rounds

.key_store:
    ; Сохраняем текущие K0, K1 как раундовые ключи
    movdqu xmm0, [rsp+16]
    movdqu xmm1, [rsp+32]
    movdqu [rsi], xmm0
    movdqu [rsi+16], xmm1
    add rsi, 32

    inc r10d
    jmp .key_groups

.key_done:
    add rsp, 64
    pop rbp
    ret

; ----------------------------------------------
;  kuznyechik_encrypt_block
;  Вход: rdi = указатель на блок (in/out)
;        rsi = указатель на expanded_key (160 байт)
; ----------------------------------------------
kuznyechik_encrypt_block:
    push rbp
    mov rbp, rsp

    mov r10, rdi
    mov r11, rsi                     ; r11 = указатель на текущий раундовый ключ
    mov ecx, 9                       ; 9 полных раундов

.enc_loop:
    ; XOR с ключом
    movdqu xmm0, [r10]
    movdqu xmm1, [r11]
    pxor xmm0, xmm1

    ; S-подстановка
    lea rdx, [rel S_box_table]
    vpshufb xmm0, xmm0, [rdx]

    ; L-преобразование
    movdqu [r10], xmm0
    mov rdi, r10
    lea r8, [rel L_table]
    call kuznyechik_L_avx2

    add r11, 16
    dec ecx
    jnz .enc_loop

    ; Последний XOR (раунд 10)
    movdqu xmm0, [r10]
    movdqu xmm1, [r11]
    pxor xmm0, xmm1
    movdqu [r10], xmm0

    pop rbp
    ret

; ----------------------------------------------
;  kuznyechik_decrypt_block
;  Вход: rdi = указатель на блок (in/out)
;        rsi = указатель на expanded_key (160 байт)
; ----------------------------------------------
kuznyechik_decrypt_block:
    push rbp
    mov rbp, rsp

    mov r10, rdi
    mov r11, rsi
    add r11, 144                    ; начинаем с K10 (последнего)
    mov ecx, 9

.dec_loop:
    ; XOR с ключом
    movdqu xmm0, [r10]
    movdqu xmm1, [r11]
    pxor xmm0, xmm1
    movdqu [r10], xmm0

    ; Обратное L
    mov rdi, r10
    lea r8, [rel InvL_table]
    call kuznyechik_L_inv_avx2

    ; Обратная S-подстановка
    movdqu xmm0, [r10]
    lea rdx, [rel InvS_box_table]
    vpshufb xmm0, xmm0, [rdx]
    movdqu [r10], xmm0

    sub r11, 16
    dec ecx
    jnz .dec_loop

    ; Последний XOR с K1
    mov r11, rsi
    movdqu xmm0, [r10]
    movdqu xmm1, [r11]
    pxor xmm0, xmm1
    movdqu [r10], xmm0

    pop rbp
    ret

; ----------------------------------------------
;  kuznyechik_encrypt_ecb
;  Вход: rdi = in, rsi = out, rdx = len, rcx = expanded_key
; ----------------------------------------------
kuznyechik_encrypt_ecb:
    push rbp
    mov rbp, rsp

    mov r10, rdi
    mov r11, rsi
    mov r12, rdx
    mov r13, 0
    mov r14, rcx

.ecb_loop:
    cmp r13, r12
    jge .ecb_done

    mov rdi, r10
    mov rsi, r14
    call kuznyechik_encrypt_block

    add r10, 16
    add r11, 16
    add r13, 16
    jmp .ecb_loop

.ecb_done:
    pop rbp
    ret

; ----------------------------------------------
;  kuznyechik_encrypt_ctr
;  Вход: rdi = in, rsi = out, rdx = len,
;        rcx = expanded_key (160 байт),
;        r8  = nonce (16 байт, счётчик в младших 8 байтах)
; ----------------------------------------------
kuznyechik_encrypt_ctr:
    push rbp
    mov rbp, rsp
    sub rsp, 64

    mov r10, rdi                     ; in
    mov r11, rsi                     ; out
    mov r12, rdx                     ; len
    mov r13, rcx                     ; expanded_key
    mov r14, r8                      ; nonce

    mov r15, 0                       ; processed

    ; Копируем nonce на стек (для инкремента)
    movdqu xmm0, [r14]
    movdqu [rsp+16], xmm0

.ctr_loop:
    cmp r15, r12
    jge .ctr_done

    ; Инкрементируем счётчик (маленький endian, младшие 8 байт)
    mov rax, [rsp+16]                ; берём младшие 8 байт nonce
    add rax, 1
    mov [rsp+16], rax

    ; Шифруем блок счётчика
    lea rdi, [rsp+16]
    mov rsi, r13
    call kuznyechik_encrypt_block

    ; XOR с данными
    movdqu xmm0, [r10]               ; данные
    movdqu xmm1, [rsp+16]            ; зашифрованный счётчик
    pxor xmm0, xmm1
    movdqu [r11], xmm0               ; сохраняем результат

    add r10, 16
    add r11, 16
    add r15, 16
    jmp .ctr_loop

.ctr_done:
    add rsp, 64
    pop rbp
    ret

